// Builds the Next.js frontend in standalone mode and copies the output into
// resources/frontend/ so electron-builder can bundle it.
//
// The Next.js `standalone` build produces:
//   frontend/.next/standalone/         -> minimal server.js + node_modules
//   frontend/.next/static/             -> static assets
//   frontend/public/                   -> public dir (must be copied into standalone)
//
// Run with: node desktop/scripts/prepare-frontend.js

const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..', '..');
const DESKTOP_DIR = path.resolve(__dirname, '..');
const FRONTEND_SRC = path.join(ROOT, 'frontend');
const STANDALONE_DIR = path.join(FRONTEND_SRC, '.next', 'standalone');
const STATIC_DIR = path.join(FRONTEND_SRC, '.next', 'static');
const PUBLIC_DIR = path.join(FRONTEND_SRC, 'public');
const RESOURCES_DIR = path.join(DESKTOP_DIR, 'resources');
const FRONTEND_DST = path.join(RESOURCES_DIR, 'frontend');
const ENV_FILE = path.join(FRONTEND_SRC, '.env.local');

const QWEN_API_KEY = 'sk-65677aded2b3454ca728cfb517ced27f';

function log(msg) {
  console.log(`\n\x1b[36m[prepare-frontend]\x1b[0m ${msg}`);
}

function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

function copyDir(src, dst) {
  ensureDir(dst);
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, entry.name);
    const d = path.join(dst, entry.name);
    if (entry.isDirectory()) copyDir(s, d);
    else if (entry.isFile()) fs.copyFileSync(s, d);
  }
}

function run(cmd, args, opts = {}) {
  log(`$ ${cmd} ${args.join(' ')}  (cwd=${opts.cwd || process.cwd()})`);
  const result = spawnSync(cmd, args, {
    stdio: 'inherit',
    shell: process.platform === 'win32',
    ...opts,
  });
  if (result.status !== 0) {
    throw new Error(`Command failed (${result.status}): ${cmd} ${args.join(' ')}`);
  }
}

function writeEnvFileIfMissing() {
  if (fs.existsSync(ENV_FILE)) {
    log(`.env.local already exists, preserving it`);
    return;
  }
  const content = [
    '# Generated by desktop/scripts/prepare-frontend.js',
    `QWEN_API_KEY=${QWEN_API_KEY}`,
    'QWEN_BASE_URL=https://dashscope.aliyuncs.com/compatible-mode/v1',
    `TTS_QWEN_API_KEY=${QWEN_API_KEY}`,
    'TTS_QWEN_BASE_URL=https://dashscope.aliyuncs.com/api/v1',
    'BACKEND_ENABLED=true',
    'BACKEND_URL=http://127.0.0.1:9527',
    '',
  ].join('\n');
  fs.writeFileSync(ENV_FILE, content, 'utf8');
  log(`wrote ${ENV_FILE}`);
}

function main() {
  writeEnvFileIfMissing();

  log('pnpm install (frontend)');
  run('pnpm', ['install', '--frozen-lockfile'], { cwd: FRONTEND_SRC });

  log('pnpm build (frontend, standalone)');
  run('pnpm', ['build'], { cwd: FRONTEND_SRC });

  if (!fs.existsSync(STANDALONE_DIR)) {
    throw new Error(`standalone output not found at ${STANDALONE_DIR}. Is next.config output: 'standalone' set?`);
  }

  log(`assembling ${FRONTEND_DST}`);
  fs.rmSync(FRONTEND_DST, { recursive: true, force: true });
  copyDir(STANDALONE_DIR, FRONTEND_DST);

  // standalone omits .next/static and public — copy them explicitly
  copyDir(STATIC_DIR, path.join(FRONTEND_DST, '.next', 'static'));
  if (fs.existsSync(PUBLIC_DIR)) {
    copyDir(PUBLIC_DIR, path.join(FRONTEND_DST, 'public'));
  }

  log('done');
}

try {
  main();
} catch (err) {
  console.error('\n\x1b[31m[prepare-frontend] failed:\x1b[0m', err);
  process.exit(1);
}
